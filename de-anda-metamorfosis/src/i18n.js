const STORAGE_KEY = 'dda-lang';
const listeners = new Set();

function initialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && STRINGS[q]) return q;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* storage non disponibile: nessun problema */
  }
  return 'es';
}

let current = initialLang();

export const getLang = () => current;
export const t = (key) => STRINGS[current][key] ?? STRINGS.es[key] ?? key;

/** Converte "*parole*" in <em>parole</em> (corsivo oro). */
export function richText(str) {
  const esc = str.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  return esc.replace(/\*(.+?)\*/g, '<em>$1</em>');
}

/** Cambio lingua istantaneo: aggiorna i testi semplici e avvisa chi ascolta. */
export function setLang(lang) {
  if (!STRINGS[lang] || lang === current) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignora */
  }
  applyStaticTexts();
  listeners.forEach((fn) => fn(lang));
}

export const onLangChange = (fn) => listeners.add(fn);

export function applyStaticTexts(root = document) {
  document.documentElement.lang = current;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.setAttribute('alt', t(el.dataset.i18nAlt));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === current)));
}
