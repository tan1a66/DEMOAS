const DICTS = { es: ES, en: EN };
let lang = 'es';
try {
  const saved = localStorage.getItem('pda-lang');
  if (saved === 'en' || saved === 'es') lang = saved;
} catch (e) { /* almacenamiento no disponible */ }

export function getLang() { return lang; }

export function t(key, vars) {
  let s = DICTS[lang][key] ?? DICTS.es[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

// Devuelve el valor según el idioma de un objeto { es, en } (para los datos).
export function L(obj) {
  if (obj == null || typeof obj !== 'object') return obj;
  return obj[lang] ?? obj.es;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
}

const listeners = new Set();
export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function setLang(next) {
  if (next !== 'es' && next !== 'en') return;
  lang = next;
  try { localStorage.setItem('pda-lang', next); } catch (e) { /* ignorar */ }
  document.documentElement.lang = next;
  document.title = t('meta.title');
  applyI18n();
  listeners.forEach((fn) => fn(next));
}
